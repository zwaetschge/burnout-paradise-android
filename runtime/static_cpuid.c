void port_cpuid(uint32_t leaf, uint32_t subleaf) {
    uint32_t v[4];
    const uint32_t count = sizeof port_cpu_leaves / sizeof port_cpu_leaves[0];
    if (gcp_query(port_cpu_leaves, count, leaf, subleaf, v)) {
        /* Intel SDM vol. 2A, CPUID: an input above the highest basic leaf (and
         * outside the extended range) returns the data of the highest basic
         * leaf. Code that only wants CPUID's serialising effect executes it
         * with whatever EAX holds (original image, 0x009327EA: pushal/cpuid/
         * rdtsc/popal). Any other gap in the table stays a named stop. */
        uint32_t basic[4], extended[4];
        int out_of_range = 0;
        if (!gcp_query(port_cpu_leaves, count, 0u, 0u, basic) &&
            !gcp_query(port_cpu_leaves, count, 0x80000000u, 0u, extended))
            out_of_range = (leaf > basic[0] && leaf < 0x80000000u) || leaf > extended[0];
        if (!out_of_range ||
            (gcp_query(port_cpu_leaves, count, basic[0], subleaf, v) &&
             gcp_query(port_cpu_leaves, count, basic[0], 0u, v)))
            port_named_stop("cpuid-leaf-unmodelled", leaf);
    }
    g_eax = v[0]; g_ebx = v[1]; g_ecx = v[2]; g_edx = v[3];
}
