#!/usr/bin/env python3
"""Pack the dynamically loaded guest code that the host run discovered
(<hot dir>/dyn/dyn_<VA>_<digest>.{c,bin,json}, written by
tools/static_hot_helper.py) into one translation unit for a static image:

  port/generated/<name>/static_dyn.c
      dyn_<VA>_<digest>()      the lifted function (was sub_<VA>)
      port_dyn_table[]         { va, lo, hi, bytes, fn }

The runtime (runtime/static_hot.c) uses an entry only while the guest memory
[lo, hi) still equals the bytes the function was lifted from; anything else is
a named stop on the device. The code bytes come from the user's own game data
(sound banks) and stay private.

Usage: tools/static_dyn_pack.py <hot dir> <out dir>
"""
import json, re, struct, sys
from pathlib import Path
from capstone import Cs, CS_ARCH_X86, CS_MODE_32, CS_OP_IMM, CS_OP_MEM
from capstone import x86_const as X

# Game image and dbdata.dll: addresses that do not move with the sound bank.
FIXED = ((0x00400000, 0x01400000), (0x10000000, 0x100C0000))

def fixed(v):
    return any(a <= v < b for a, b in FIXED)

def relocation(code, lo, hi):
    """The same function is loaded at other heap addresses (another language
    loads other banks first). Relative to the bytes lifted at `lo`, a copy at
    lo+d differs only in two kinds of 4-byte fields:
      ext: rel32 of a call/jmp/jcc leaving [lo, hi)     (stored value - d)
      int: absolute imm32/disp32 pointing into [lo, hi) (stored value + d)
    Returns (ext offsets, int offsets) or None when the function cannot be
    moved (a rel8 leaving the function, or an absolute address into another
    heap object, which would not move by the same d)."""
    md = Cs(CS_ARCH_X86, CS_MODE_32); md.detail = True
    ext, inner = [], []
    end = lo
    for insn in md.disasm(code, lo):
        end = insn.address + insn.size
        rel = insn.group(X.X86_GRP_JUMP) or insn.group(X.X86_GRP_CALL)
        for op in insn.operands:
            if op.type == CS_OP_IMM:
                v = op.imm & 0xFFFFFFFF
                if rel:
                    if lo <= v < hi: continue
                    if insn.imm_size != 4: return None
                    ext.append(insn.address - lo + insn.imm_offset)
                elif insn.imm_size == 4 and not fixed(v) and v >= 0x10000:
                    if lo <= v < hi: inner.append(insn.address - lo + insn.imm_offset)
                    elif 0x01400000 <= v < 0x80000000: return None
            elif op.type == CS_OP_MEM and op.mem.base == 0 and op.mem.index == 0:
                v = op.mem.disp & 0xFFFFFFFF
                if fixed(v) or v < 0x10000: continue
                if lo <= v < hi and insn.disp_size == 4: inner.append(insn.address - lo + insn.disp_offset)
                else: return None
    if end < hi - 1: return None                  # bytes capstone could not decode (the guard still compares any tail byte exactly)
    return ext, inner

def shift_literals(body, lo, hi):
    """Every address literal inside the function becomes base-relative."""
    def repl(m):
        v = int(m.group(1), 16)
        return f'(0x{v:08X}u + _dd)' if lo <= v < hi else m.group(0)
    body = re.sub(r'0x([0-9A-Fa-f]{8})u', repl, body)
    # the delta of this call, read once on entry (nested dispatch may change it)
    return re.sub(r'(void dyn_\w+\(void\) \{\n)', r'\1    const uint32_t _dd = port_dyn_delta;\n', body, count=1)

def main():
    hot, out = Path(sys.argv[1]) / 'dyn', Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    parts = ['/* Generated by tools/static_dyn_pack.py - DO NOT EDIT. Private: contains game code bytes. */',
             '#define RECOMP_GENERATED_CODE', '#include "recomp_types.h"', '#include "recomp_unsupported.h"',
             '#include <math.h>', '#include <string.h>',
             '/* runtime/static_hot.c: load address of this call minus the address the function was lifted at */',
             'extern RECOMP_TLS uint32_t port_dyn_delta;', '']
    rows = []
    moved = 0
    for meta_path in sorted(hot.glob('dyn_*.json')):
        meta = json.loads(meta_path.read_text())
        stem = meta_path.stem                      # dyn_<VA>_<digest>
        src = meta_path.with_suffix('.c').read_text()
        code = meta_path.with_suffix('.bin').read_bytes()
        va = meta['va']
        sub = f'sub_{va:08X}'
        body = src[src.index(f'void {sub}(void);'):]
        body = re.sub(rf'\b{sub}\b', stem, body)
        lo, hi = meta['lo'], meta['hi']
        reloc = relocation(code, lo, hi)
        body = shift_literals(body, lo, hi) if reloc else re.sub(r'(void dyn_\w+\(void\) \{\n)', r'\1    const uint32_t _dd = 0;\n', body, count=1)
        parts.append(f'/* ---- {stem}: {meta["instructions"]} instructions, guest [0x{lo:08X}, 0x{hi:08X}), '
                     f'{"movable: %d rel, %d abs fields" % (len(reloc[0]), len(reloc[1])) if reloc else "fixed address"} ---- */')
        parts.append(body)
        parts.append(f'static const unsigned char {stem}_bytes[{len(code)}] = {{' + ','.join(str(b) for b in code) + '};')
        ext, inner = reloc if reloc else ([], [])
        parts.append(f'static const unsigned short {stem}_ext[] = {{' + ','.join(map(str, ext + [0xFFFF])) + '};')
        parts.append(f'static const unsigned short {stem}_int[] = {{' + ','.join(map(str, inner + [0xFFFF])) + '};')
        rows.append(f'    {{ 0x{va:08X}u, 0x{lo:08X}u, 0x{hi:08X}u, {stem}_bytes, {stem}, {1 if reloc else 0}, {stem}_ext, {stem}_int }},')
        moved += 1 if reloc else 0
    parts.append('typedef struct { uint32_t va, lo, hi; const unsigned char *bytes; void (*fn)(void);')
    parts.append('                 unsigned movable; const unsigned short *ext, *inner; } PortDynEntry;')
    parts.append('const PortDynEntry port_dyn_table[] = {')
    parts.extend(rows)
    parts.append('    { 0, 0, 0, 0, 0, 0, 0, 0 }')
    parts.append('};')
    parts.append(f'const unsigned port_dyn_count = {len(rows)};')
    (out / 'static_dyn.c').write_text('\n'.join(parts) + '\n')
    print(f'packed {len(rows)} dynamic functions ({moved} movable) into {out / "static_dyn.c"}')

if __name__ == '__main__':
    main()
